-- Clubes (RN10). Valor do elenco e patrimônio são calculados a cada consulta e não são colunas.
CREATE TABLE clubes (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(60)    NOT NULL,
    -- nome depois da V4 em minúsculas, calculado pela aplicação: garante a RN10 no banco
    -- (sem diferenciar maiúsculas e minúsculas, mas considerando acentos), sem depender do locale do servidor
    nome_chave  VARCHAR(120)   NOT NULL,
    sigla       CHAR(3)        NOT NULL,
    caixa       NUMERIC(10, 2) NOT NULL DEFAULT 300.00,
    formacao    VARCHAR(5),
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_clubes_nome_chave UNIQUE (nome_chave),
    CONSTRAINT uk_clubes_sigla UNIQUE (sigla),
    CONSTRAINT ck_clubes_sigla CHECK (sigla ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_clubes_caixa CHECK (caixa >= 0),
    CONSTRAINT ck_clubes_formacao CHECK (formacao IN ('3-1', '2-2', '2-1-1', '1-2-1'))
);

ALTER TABLE jogadores
    ADD CONSTRAINT fk_jogadores_clube FOREIGN KEY (clube_id) REFERENCES clubes (id);
