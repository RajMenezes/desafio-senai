-- Jogadores (RN02 a RN09). Overall e valor de mercado são calculados a cada consulta e não são colunas.
-- A FK de clube_id para clubes.id é criada junto com a tabela clubes.
CREATE TABLE jogadores
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100)             NOT NULL,
    posicao       VARCHAR(3)               NOT NULL,
    agilidade     INTEGER                  NOT NULL,
    idade         INTEGER                  NOT NULL,
    valor_base    NUMERIC(6, 2)            NOT NULL,
    condicao      VARCHAR(20)              NOT NULL DEFAULT 'APTO',
    clube_id      INTEGER,
    velocidade    INTEGER                  NOT NULL,
    finalizacao   INTEGER                  NOT NULL,
    passe         INTEGER                  NOT NULL,
    drible        INTEGER                  NOT NULL,
    defesa        INTEGER                  NOT NULL,
    fisico        INTEGER                  NOT NULL,
    potencial     INTEGER                  NOT NULL,
    excluido_em   TIMESTAMP WITH TIME ZONE,
    criado_em     TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT ck_jogadores_posicao CHECK (posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA')),
    CONSTRAINT ck_jogadores_condicao CHECK (condicao IN ('APTO', 'MAL_CONDICIONADO', 'DOENTE')),
    CONSTRAINT ck_jogadores_agilidade CHECK (agilidade BETWEEN 1 AND 100),
    CONSTRAINT ck_jogadores_idade CHECK (idade BETWEEN 16 AND 45),
    CONSTRAINT ck_jogadores_valor_base CHECK (valor_base >= 1.00),
    CONSTRAINT ck_jogadores_atributos CHECK (
        velocidade BETWEEN 1 AND 99 AND finalizacao BETWEEN 1 AND 99 AND passe BETWEEN 1 AND 99
            AND drible BETWEEN 1 AND 99 AND defesa BETWEEN 1 AND 99 AND fisico BETWEEN 1 AND 99
            AND velocidade + finalizacao + passe + drible + defesa + fisico <= 480),
    CONSTRAINT ck_jogadores_potencial CHECK (
        potencial BETWEEN 1 AND 99
            AND potencial >= GREATEST(velocidade, finalizacao, passe, drible, defesa, fisico))
);

CREATE INDEX ix_jogadores_clube_id ON jogadores (clube_id);
