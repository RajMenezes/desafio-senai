-- Contratos (RN12, RN15). Dias restantes e percentual de multa são calculados a cada consulta.
CREATE TABLE contratos (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jogador_id      INTEGER       NOT NULL REFERENCES jogadores (id),
    clube_id        INTEGER       NOT NULL REFERENCES clubes (id),
    valor_compra    NUMERIC(6, 2) NOT NULL,
    fidelidade_ate  TIMESTAMP WITH TIME ZONE NOT NULL,
    situacao        VARCHAR(12)   NOT NULL,
    iniciado_em     TIMESTAMP WITH TIME ZONE NOT NULL,
    encerrado_em    TIMESTAMP WITH TIME ZONE,

    CONSTRAINT ck_contratos_situacao CHECK (situacao IN ('ATIVO', 'ENCERRADO', 'RESCINDIDO')),
    CONSTRAINT ck_contratos_valor_compra CHECK (valor_compra >= 0),
    CONSTRAINT ck_contratos_fidelidade CHECK (fidelidade_ate > iniciado_em),
    CONSTRAINT ck_contratos_encerramento CHECK ((situacao = 'ATIVO') = (encerrado_em IS NULL))
);

-- um jogador tem no máximo um contrato ATIVO
CREATE UNIQUE INDEX ux_contratos_ativo_por_jogador ON contratos (jogador_id) WHERE situacao = 'ATIVO';
CREATE INDEX ix_contratos_clube_situacao ON contratos (clube_id, situacao);

-- Transações (RN17): valores e nome do momento, nunca recalculados.
CREATE TABLE transacoes (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clube_id        INTEGER       NOT NULL REFERENCES clubes (id),
    jogador_id      INTEGER       NOT NULL REFERENCES jogadores (id),
    nome_jogador    VARCHAR(100)  NOT NULL,
    tipo            VARCHAR(6)    NOT NULL,
    valor           NUMERIC(6, 2) NOT NULL,
    taxa            NUMERIC(6, 2) NOT NULL,
    multa           NUMERIC(6, 2) NOT NULL,
    lucro           NUMERIC(7, 2),
    variacao_caixa  NUMERIC(8, 2) NOT NULL,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT ck_transacoes_tipo CHECK (tipo IN ('COMPRA', 'VENDA')),
    CONSTRAINT ck_transacoes_valores CHECK (valor >= 0 AND taxa >= 0 AND multa >= 0),
    CONSTRAINT ck_transacoes_compra CHECK (tipo <> 'COMPRA' OR (multa = 0 AND lucro IS NULL)),
    CONSTRAINT ck_transacoes_venda CHECK (tipo <> 'VENDA' OR lucro IS NOT NULL)
);

-- histórico do clube: mais recente primeiro, empate por id decrescente (RN17)
CREATE INDEX ix_transacoes_clube_criado ON transacoes (clube_id, criado_em DESC, id DESC);
CREATE INDEX ix_transacoes_clube_jogador ON transacoes (clube_id, jogador_id);
